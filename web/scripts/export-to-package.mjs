// Copies the static export into the Python package, where FastAPI serves it
// at "/". The copy is committed, like the classic interface's built files, so
// installing the package needs no Node toolchain.
import { cpSync, existsSync, rmSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const out = fileURLToPath(new URL("../out", import.meta.url));
const target = fileURLToPath(new URL("../../src/isnad_core/api/web", import.meta.url));

if (!existsSync(out)) {
  console.error("No build found in web/out — run `npm run build` first.");
  process.exit(1);
}
rmSync(target, { recursive: true, force: true });
cpSync(out, target, { recursive: true });
// Marks the directory as generated; FastAPI checks for index.html.
writeFileSync(`${target}/GENERATED.txt`, "Generated by web/scripts/export-to-package.mjs from web/. Do not edit.\n");
console.log(`exported ${out} -> ${target}`);
